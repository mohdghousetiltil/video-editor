// Builds db/seed.sql from what the app already knows (looks, model catalog, provider routes, radio stations).
//   node db/make_seed.js           (re-run it whenever lib/themes.js, lib/models.js or public/music.js change)
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const { LOOKS } = require(path.join(root, "lib", "themes"));
const models = require(path.join(root, "lib", "models"));
const providers = require(path.join(root, "lib", "providers"));
const hing = require(path.join(root, "lib", "hinglish"));

const q = (v) => (v == null ? "NULL" : "'" + String(v).replace(/'/g, "''") + "'");
const arr = (a) => (a && a.length ? "ARRAY[" + a.map(q).join(",") + "]::text[]" : "'{}'::text[]");
const iarr = (a) => (a && a.length ? "ARRAY[" + a.join(",") + "]::integer[]" : "NULL");
const out = [];
const w = (s = "") => out.push(s);

w("-- Generated by db/make_seed.js from the app's own code. Safe to run more than once.");
w("BEGIN;");
w();
w("-- the single local user (the app is single-user today; add rows here to make it multi-user)");
w("INSERT INTO app_users (id, display_name) VALUES ('00000000-0000-0000-0000-000000000001', 'Me') ON CONFLICT DO NOTHING;");
w("INSERT INTO user_settings (owner_id) VALUES ('00000000-0000-0000-0000-000000000001') ON CONFLICT DO NOTHING;");
w("INSERT INTO user_look (owner_id, look_id) VALUES ('00000000-0000-0000-0000-000000000001', NULL) ON CONFLICT DO NOTHING;");
w("INSERT INTO user_radio (owner_id) VALUES ('00000000-0000-0000-0000-000000000001') ON CONFLICT DO NOTHING;");
w("INSERT INTO director_budgets (owner_id, page, amount_usd) VALUES");
w(["clip 0.50", "story 2.00", "ugc 0.50", "poses 0.15", "motion 0.50"].map((x) => { const [p, a] = x.split(" "); return `  ('00000000-0000-0000-0000-000000000001', '${p}', ${a})`; }).join(",\n") + "\nON CONFLICT DO NOTHING;");
w();

w("INSERT INTO providers (id, name, external, job_prefix) VALUES");
w("  ('openrouter', 'OpenRouter', false, NULL),\n  ('fal', 'fal.ai', true, 'fal_'),\n  ('byteplus', 'BytePlus ModelArk', true, 'bp_')\nON CONFLICT (id) DO NOTHING;");
w();

// ---- models: the app's video catalog, plus a stub for any model a look points at ----
const VIDEO = models.VIDEO || {};
const known = models.KNOWN || {};
const ids = new Set(Object.keys(VIDEO));
for (const l of LOOKS) { if (l.models.cheap) ids.add(l.models.cheap); if (l.models.good) ids.add(l.models.good); }
w("INSERT INTO ai_models (id, kind, name, tier, quality, has_audio, speaks_hindi, durations_s, resolutions, aspects, frames, tags, price_table, price_sound_usd_s, price_silent_usd_s, hidden, notes) VALUES");
// per-second price at 720p (or the first listed resolution): [with sound, silent]
const base = (p) => { const e = p["720p"] || Object.values(p)[0]; return e ? [e[0], e[1]] : ["NULL", "NULL"]; };
const rows = [];
for (const id of [...ids].sort()) {
  const m = VIDEO[id] || {}, k = known[id] || {};
  const prices = m.price || {};
  rows.push(`  (${q(id)}, 'video', ${q(m.name || id)}, ${q(m.tier || null)}, ${k.q != null ? k.q : "NULL"}, ${m.audio ? "true" : "false"}, ${hing.hindiSpeech(id) ? "true" : "false"}, ` +
    `${iarr(m.durs)}, ${m.res ? arr(m.res) : "NULL"}, ${m.asp ? arr(m.asp) : "NULL"}, ${m.frames ? arr(m.frames) : "NULL"}, ${arr(k.tags)}, ${q(JSON.stringify(prices))}::jsonb, ${base(prices)[0]}, ${base(prices)[1]}, ${m.hidden ? "true" : "false"}, ${q(m.note || null)})`);
}
w(rows.join(",\n"));
w("ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, has_audio = EXCLUDED.has_audio, speaks_hindi = EXCLUDED.speaks_hindi, price_table = EXCLUDED.price_table, price_sound_usd_s = EXCLUDED.price_sound_usd_s, price_silent_usd_s = EXCLUDED.price_silent_usd_s;");
w();

// ---- extra routes (fal.ai Kling, BytePlus Seedance) ----
const routeRows = [];
for (const [model, list] of Object.entries(providers.ROUTES)) {
  if (!ids.has(model)) continue;
  for (const r of list) {
    routeRows.push(`  (${q(model)}, ${q(r.provider)}, ${q(r.app ? r.app() : r.model ? r.model() : null)}, ${q(r.appI2V ? r.appI2V() : null)}, ${r.factor ? r.factor() : 1}, ${r.price ? r.price() : "NULL"})`);
  }
}
if (routeRows.length) {
  w("INSERT INTO model_routes (model_id, provider_id, remote_app, remote_app_i2v, factor, flat_usd_s) VALUES");
  w(routeRows.join(",\n") + "\nON CONFLICT (model_id, provider_id) DO UPDATE SET remote_app = EXCLUDED.remote_app, factor = EXCLUDED.factor, flat_usd_s = EXCLUDED.flat_usd_s;");
  w();
}

// ---- looks ----
w("INSERT INTO looks (id, name, icon, swatch, style, lighting, camera, avoid, cheap_model, good_model, resolution, voice, caption_style, music_mood, effect, builtin, sort_order) VALUES");
w(LOOKS.map((l, i) => `  (${q(l.id)}, ${q(l.name)}, ${q(l.icon)}, ${arr(l.swatch)}, ${q(l.style)}, ${q(l.lighting)}, ${q(l.camera)}, ${q(l.avoid || null)}, ${q(l.models.cheap)}, ${q(l.models.good)}, ${q(l.models.res || "720p")}, ${q(l.voice)}, ${q(l.capStyle)}, ${q(l.music)}, ${q(l.look || "clean")}, true, ${(i + 1) * 10})`).join(",\n") +
  "\nON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name, style = EXCLUDED.style, lighting = EXCLUDED.lighting, camera = EXCLUDED.camera, avoid = EXCLUDED.avoid, cheap_model = EXCLUDED.cheap_model, good_model = EXCLUDED.good_model;");
w();

// ---- radio stations (the list in public/music.js) ----
const music = fs.readFileSync(path.join(root, "public", "music.js"), "utf8");
const stations = [...music.matchAll(/\{ name: '([^']+)', tag: '([^']*)', url: '([^']+)' \}/g)].map((m) => ({ name: m[1], tag: m[2], url: m[3] }));
const genre = (t) => (/synthwave|synth/i.test(t) ? "synth" : /vapor|retro|80s|lounge|spy/i.test(t) ? "retro" : "electro");
w("INSERT INTO radio_stations (name, tag, url, genre, sort_order) VALUES");
w(stations.map((s, i) => `  (${q(s.name)}, ${q(s.tag)}, ${q(s.url)}, ${q(genre(s.tag))}, ${(i + 1) * 10})`).join(",\n") + "\nON CONFLICT (url) DO NOTHING;");
w();
w("COMMIT;");

fs.writeFileSync(path.join(__dirname, "seed.sql"), out.join("\n") + "\n");
console.log(`seed.sql: ${ids.size} models, ${routeRows.length} routes, ${LOOKS.length} looks, ${stations.length} stations`);
